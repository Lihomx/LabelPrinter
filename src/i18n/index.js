export const t = (path, params = {}) => {
  const keys = path.split('.');
  let res = messages[currentLang.value];
  for (const k of keys) {
    if (!res || res[k] === undefined) {
      // Fallback to zh if missing in current lang
      let fb = messages.zh;
      for (const fbk of keys) {
        if (!fb || fb[fbk] === undefined) return path;
        fb = fb[fbk];
      }
      res = fb;
      break;
    }
    res = res[k];
  }
  if (typeof res === 'string' && params && Object.keys(params).length > 0) {
    return res.replace(/\{(\w+)\}/g, (_, key) => params[key] !== undefined ? params[key] : `{${key}}`);
  }
  return res;
};
